"""Package small native HomeLib adapters for on-demand DOC/DjVu installation.

Both host architectures use these same verified x86/AnyCPU adapters. The
vendor libraries remain separate author downloads. No user data is included.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import zipfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('output', type=Path)
    parser.add_argument('--revision', type=int, required=True)
    parser.add_argument('--write-pins', action='store_true')
    args = parser.parse_args()
    if not 1 <= args.revision <= 999:
        parser.error('revision must be between 1 and 999')
    repo = Path(__file__).resolve().parents[1]
    source = (repo/'Program/Units/unit_ReaderAdapters.pas').read_text('utf-8-sig')
    args.output.mkdir(parents=True, exist_ok=False)
    report, pins = [], []
    for component, label in [('DocSharp', 'DOC'), ('DjVuLibre', 'DjVu')]:
        section = source.split("if ID='"+component+"' then", 1)[1].split(');', 1)[0]
        names = re.findall(r"'([^']+)'", section)
        payload = {}
        for name in names:
            a = (repo/'Program/Out/Bin'/name).read_bytes()
            b = (repo/'Program/Out/Bin64'/name).read_bytes()
            assert a == b, 'A shared adapter differs between runtimes: '+name
            payload[name] = a
        assert payload and all(x.startswith(('tools/doc/', 'tools/djvu/')) for x in payload)
        name = f'HomeLibRu-{label}-adapter-{args.revision}.zip'
        path = args.output/name
        with path.open('xb') as stream, zipfile.ZipFile(stream, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as archive:
            for member, data in sorted(payload.items()):
                info = zipfile.ZipInfo(member, (2026, 10, 27, 0, 0, 0))
                info.compress_type = zipfile.ZIP_DEFLATED
                info.external_attr = 0o644 << 16
                archive.writestr(info, data)
        with zipfile.ZipFile(path) as archive:
            assert archive.testzip() is None
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        size = path.stat().st_size
        report.append(dict(id=component, name=name, size=size, sha256=digest, files=names))
        pins.append(f"  (ID:'{component}'; Name:'{name}'; SHA256:'{digest}'; Size:{size})")
    (args.output/'reader-adapter-report.json').write_text(json.dumps(report, indent=2)+'\n', encoding='utf-8')
    if args.write_pins:
        text = '// Generated by scripts/package-reader-adapters.py; immutable versioned ZIPs.\n'
        text += 'const READER_ADAPTER_PACKAGES: array[0..1] of TReaderAdapterPackage = (\n'
        text += ',\n'.join(pins)+');\n'
        (repo/'Program/Units/ReaderAdapterPackages.inc').write_text(text, encoding='utf-8-sig', newline='\r\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
