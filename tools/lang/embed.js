'use strict';

// Each catalog is linked with its LANG_<CODE>_SIG: the loader verifies the pair,
// which stops a resource editor adding a language to a shipped exe.
//
// A missing catalog is not an error: a clean clone has no Program/Lang (private
// repo) and must still build Ukrainian-only. A present but unsigned catalog
// fails, since it would silently ship one language fewer.

const fs = require('fs');
const path = require('path');

const { EMBEDDED } = require('./embedded_locales');
const ROOT = path.join(__dirname, '..', '..');
const LANG_DIR = path.join(ROOT, 'Program', 'Lang');
const RC_PATH = path.join(ROOT, 'Program', 'lang.rc');

const lines = [
  '// Generated by tools/lang/embed.js -- do not edit by hand.',
  '// Paths are relative to this file, which lives in Program\\.',
  '',
];

const embedded = [];
for (const code of EMBEDDED) {
  const file = path.join(LANG_DIR, `${code}.json`);
  if (!fs.existsSync(file)) continue;

  // The loader would silently ignore an invalid or mislabelled catalog.
  let doc;
  try {
    doc = JSON.parse(fs.readFileSync(file, 'utf8').replace(/^﻿/, ''));
  } catch (e) {
    console.error(`ERROR: ${code}.json is not valid JSON: ${e.message}`);
    process.exit(1);
  }
  if (doc.locale !== code) {
    console.error(`ERROR: ${code}.json declares locale "${doc.locale}"`);
    process.exit(1);
  }

  if (!fs.existsSync(`${file}.sig`)) {
    console.error(`ERROR: ${code}.json has no ${code}.json.sig -- the loader `
      + `would refuse it, and the exe would ship without ${code}.`);
    console.error(`       Sign it: node tools/lang/sign.js Program/Lang/${code}.json`);
    process.exit(1);
  }

  lines.push(`LANG_${code.toUpperCase()} RCDATA "Lang\\\\${code}.json"`);
  lines.push(`LANG_${code.toUpperCase()}_SIG RCDATA "Lang\\\\${code}.json.sig"`);
  embedded.push(code);
}

if (embedded.length === 0) {
  lines.push('// No catalogs present -- Ukrainian-only build.');
}

fs.writeFileSync(RC_PATH, lines.join('\r\n') + '\r\n', 'utf8');
console.log(`lang.rc written: ${embedded.length ? embedded.join(', ') : 'no catalogs'}`);
